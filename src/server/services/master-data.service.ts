import { type Prisma } from "@prisma/client";
import prisma from "@/lib/prisma";
import { errors } from "@/lib/errors";
import { actor, writeAudit, type AuditEntity } from "@/lib/audit";
import { nextMasterCode } from "@/lib/numbering";
import type { ServiceActor } from "@/server/services/order.service";

/**
 * Admin master data (spec Section 7.8).
 * Master data is never hard-deleted: records are deactivated so historical
 * orders, delivery orders and ledger rows keep resolving their references.
 */

export type ProductInput = {
  code: string;
  name: string;
  category: string;
  unit?: string;
  isActive?: boolean;
};

export async function listProducts(includeInactive = true) {
  const products = await prisma.product.findMany({
    where: includeInactive ? {} : { isActive: true },
    orderBy: { name: "asc" },
  });
  return products.map((product) => ({
    code: product.code,
    name: product.name,
    category: product.category,
    unit: product.unit,
    isActive: product.isActive,
  }));
}

export async function saveProduct(input: ProductInput, admin: ServiceActor, ip?: string) {
  const before = await prisma.product.findUnique({ where: { code: input.code } });
  const product = await prisma.product.upsert({
    where: { code: input.code },
    create: {
      code: input.code,
      name: input.name,
      category: input.category,
      unit: input.unit ?? "MT",
      isActive: input.isActive ?? true,
      createdBy: admin.id,
    },
    update: {
      name: input.name,
      category: input.category,
      unit: input.unit ?? "MT",
      isActive: input.isActive ?? true,
    },
  });

  await writeAudit({
    ...actor(admin, ip),
    action: before ? "UPDATE" : "CREATE",
    entity: "product",
    entityId: product.code,
    oldValue: before ? { name: before.name, category: before.category, isActive: before.isActive } : undefined,
    newValue: { name: product.name, category: product.category, isActive: product.isActive },
  });

  return product;
}

export type CustomerInput = {
  /** Omit to create: the system generates CUS-000001, CUS-000002 … (never typed). */
  code?: string | null;
  name: string;
  phone?: string | null;
  address?: string | null;
  creditLimit?: string | null;
  isActive?: boolean;
};

export async function listCustomers(filter: { q?: string; isActive?: boolean } = {}) {
  const where: Prisma.CustomerWhereInput = {
    ...(filter.isActive === undefined ? {} : { isActive: filter.isActive }),
    ...(filter.q
      ? {
          OR: [
            { name: { contains: filter.q, mode: "insensitive" } },
            { code: { contains: filter.q, mode: "insensitive" } },
            { phone: { contains: filter.q, mode: "insensitive" } },
          ],
        }
      : {}),
  };
  const customers = await prisma.customer.findMany({ where, orderBy: { name: "asc" } });
  return customers.map((customer) => ({
    code: customer.code,
    name: customer.name,
    phone: customer.phone,
    address: customer.address,
    creditLimit: customer.creditLimit?.toFixed(2) ?? null,
    isActive: customer.isActive,
  }));
}

export type CustomerRow = Awaited<ReturnType<typeof listCustomers>>[number];

/**
 * Creates or updates a customer.
 *
 * The **code is generated by the system** (CUS-000001 …) and is never editable:
 * a new customer is created without a code, and an existing one is always
 * addressed by its stored code. That keeps the identifier stable for orders,
 * delivery orders and the stock ledger.
 */
export async function saveCustomer(input: CustomerInput, admin: ServiceActor, ip?: string) {
  return prisma.$transaction(async (tx) => {
    let code = input.code?.trim().toUpperCase();
    const before = code ? await tx.customer.findUnique({ where: { code } }) : null;

    // No code supplied (create) - or a code that does not exist yet and was not
    // meant as an update: allocate the next one.
    if (!code) code = await nextMasterCode("customer", tx);

    const customer = await tx.customer.upsert({
      where: { code },
      create: {
        code,
        name: input.name,
        phone: input.phone ?? null,
        address: input.address ?? null,
        creditLimit: input.creditLimit ?? null,
        isActive: input.isActive ?? true,
        createdBy: admin.id,
      },
      update: {
        name: input.name,
        phone: input.phone ?? null,
        address: input.address ?? null,
        creditLimit: input.creditLimit ?? null,
        isActive: input.isActive ?? true,
      },
    });

    await writeAudit(
      {
        ...actor(admin, ip),
        action: before ? "UPDATE" : "CREATE",
        entity: "customer",
        entityId: customer.code,
        oldValue: before
          ? {
              name: before.name,
              creditLimit: before.creditLimit?.toFixed(2) ?? null,
              isActive: before.isActive,
            }
          : undefined,
        newValue: {
          name: customer.name,
          creditLimit: customer.creditLimit?.toFixed(2) ?? null,
          isActive: customer.isActive,
        },
      },
      tx,
    );

    return customer;
  });
}

