import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import { existsSync } from "node:fs";
import { toZonedDateTimeString } from "@/lib/dates";
import type { ReportDefinition, ReportRow } from "@/server/services/report.service";

/**
 * Excel (`exceljs`) and PDF (`pdfkit`) exports for every report, plus the
 * printable documents (order confirmation, DO copy, dispatch challan).
 *
 * Font note: pdfkit's built-in Helvetica cannot encode the ৳ sign or Bengali
 * script. Set `PDF_FONT_PATH` to a Unicode TTF (e.g. NotoSansBengali-Regular.ttf)
 * and the exporter will use it — see docs/HUMAN_TODO.md. Until then PDF output
 * uses the ASCII-safe `BDT` marker while the on-screen UI always shows ৳.
 */

const PDF_FONT_PATH = process.env.PDF_FONT_PATH ?? "";
const unicodeFontAvailable = Boolean(PDF_FONT_PATH) && existsSync(PDF_FONT_PATH);

function pdfText(value: string): string {
  if (unicodeFontAvailable) return value;
  return value.replace(/৳/g, "BDT ");
}

function registerFonts(doc: PDFKit.PDFDocument): void {
  if (unicodeFontAvailable) {
    doc.registerFont("body", PDF_FONT_PATH);
    doc.registerFont("bold", PDF_FONT_PATH);
    doc.font("body");
  }
}

export type ExportMeta = {
  title: string;
  subtitle?: string;
  generatedBy: string;
  generatedAt?: Date;
  filterNote?: string;
};

// ---------------------------------------------------------------------------
// Excel
// ---------------------------------------------------------------------------

export async function reportsToExcel(
  reports: { report: ReportDefinition; rows: ReportRow[] }[],
  meta: ExportMeta,
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "Bulk Commodity Sales ERP";
  workbook.created = new Date();

  for (const { report, rows } of reports) {
    const sheetName = report.title.slice(0, 31);
    const sheet = workbook.addWorksheet(sheetName, {
      views: [{ state: "frozen", ySplit: 4 }],
    });

    sheet.mergeCells(1, 1, 1, Math.max(1, report.columns.length));
    const titleCell = sheet.getCell(1, 1);
    titleCell.value = report.title;
    titleCell.font = { bold: true, size: 14 };

    sheet.mergeCells(2, 1, 2, Math.max(1, report.columns.length));
    sheet.getCell(2, 1).value = `${meta.subtitle ?? ""} ${meta.filterNote ?? ""}`.trim();
    sheet.getCell(2, 1).font = { size: 10, italic: true };

    const headerRow = sheet.getRow(4);
    report.columns.forEach((column, index) => {
      const cell = headerRow.getCell(index + 1);
      cell.value = column.label;
      cell.font = { bold: true };
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE2E8F0" } };
      cell.border = {
        bottom: { style: "thin", color: { argb: "FF94A3B8" } },
      };
      sheet.getColumn(index + 1).width = column.width ?? Math.max(12, column.label.length + 4);
      sheet.getColumn(index + 1).alignment = {
        horizontal: column.align ?? (column.kind === "text" ? "left" : "right"),
      };
    });

    rows.forEach((row, rowIndex) => {
      const excelRow = sheet.getRow(5 + rowIndex);
      report.columns.forEach((column, columnIndex) => {
        const raw = row[column.key] ?? "";
        const cell = excelRow.getCell(columnIndex + 1);
        if (column.kind === "number" || column.kind === "mt" || column.kind === "money") {
          const numeric = Number(raw);
          cell.value = Number.isFinite(numeric) ? numeric : raw;
          cell.numFmt = column.kind === "money" ? "#,##0.00" : "#,##0.000";
        } else {
          cell.value = raw;
        }
      });
      excelRow.commit();
    });

    sheet.autoFilter = {
      from: { row: 4, column: 1 },
      to: { row: 4, column: report.columns.length },
    };

    const footerRow = sheet.getRow(5 + rows.length + 1);
    footerRow.getCell(1).value = `Generated by ${meta.generatedBy} on ${toZonedDateTimeString(
      meta.generatedAt ?? new Date(),
    )} (Asia/Dhaka)`;
    footerRow.getCell(1).font = { size: 9, italic: true, color: { argb: "FF64748B" } };
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

// ---------------------------------------------------------------------------
// PDF — tabular reports
// ---------------------------------------------------------------------------

export async function reportsToPdf(
  reports: { report: ReportDefinition; rows: ReportRow[] }[],
  meta: ExportMeta,
): Promise<Buffer> {
  return renderPdf((doc) => {
    for (const [reportIndex, { report, rows }] of reports.entries()) {
      if (reportIndex > 0) doc.addPage();

      doc.fontSize(16).text(pdfText(report.title));
      doc.moveDown(0.2);
      doc.fontSize(9).fillColor("#475569").text(pdfText(report.description));
      doc
        .fontSize(8)
        .text(
          pdfText(
            `Generated by ${meta.generatedBy} on ${toZonedDateTimeString(
              meta.generatedAt ?? new Date(),
            )}${meta.filterNote ? ` • ${meta.filterNote}` : ""}`,
          ),
        );
      doc.fillColor("#0f172a").moveDown(0.6);

      if (rows.length === 0) {
        doc.fontSize(10).text("No data for the selected filters.");
        continue;
      }

      const columns = report.columns;
      const left = doc.page.margins.left;
      const usable = doc.page.width - doc.page.margins.left - doc.page.margins.right;
      const colWidth = usable / columns.length;

      const drawHeader = () => {
        const y = doc.y;
        doc.fontSize(8).fillColor("#0f172a");
        columns.forEach((column, index) => {
          doc.text(pdfText(column.label), left + index * colWidth, y, {
            width: colWidth - 4,
            align: column.align === "right" ? "right" : "left",
            lineBreak: false,
          });
        });
        doc.moveDown(0.4);
        doc
          .moveTo(left, doc.y)
          .lineTo(left + usable, doc.y)
          .strokeColor("#94a3b8")
          .stroke();
        doc.moveDown(0.3);
      };

      drawHeader();

      for (const row of rows) {
        if (doc.y > doc.page.height - doc.page.margins.bottom - 24) {
          doc.addPage();
          drawHeader();
        }
        const y = doc.y;
        doc.fontSize(8);
        columns.forEach((column, index) => {
          const raw = row[column.key] ?? "";
          doc.text(pdfText(String(raw)), left + index * colWidth, y, {
            width: colWidth - 4,
            align: column.align === "right" ? "right" : "left",
            lineBreak: false,
          });
        });
        doc.moveDown(0.35);
      }

      const total = (key: string) =>
        rows.reduce((acc, row) => acc + (Number(row[key]) || 0), 0).toFixed(2);
      const numericColumns = columns.filter((c) => c.kind === "money" || c.kind === "mt");
      if (numericColumns.length > 0) {
        doc.moveDown(0.4);
        doc.fontSize(8).fillColor("#334155");
        doc.text(
          pdfText(
            numericColumns.map((c) => `${c.label}: ${total(c.key)}`).join("   |   "),
          ),
        );
        doc.fillColor("#0f172a");
      }
    }
  });
}

