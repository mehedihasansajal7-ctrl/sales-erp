export type PrintableBlock =
  | { type: "title"; text: string; align?: "left" | "center" | "right" }
  | { type: "subtitle"; text: string; align?: "left" | "center" | "right" }
  | { type: "keyValues"; items: [string, string][]; columns?: 1 | 2 }
  | { type: "table"; columns: string[]; rows: string[][]; align?: ("left" | "right")[] }
  | { type: "note"; text: string }
  | { type: "spacer"; height?: number }
  | { type: "signature"; labels: string[] };

export type PrintableDocument = {
  blocks: PrintableBlock[];
};

export async function renderPrintableToPdf(document: PrintableDocument): Promise<Buffer> {
  return renderPdf((doc) => {
    const left = doc.page.margins.left;
    const usable = doc.page.width - doc.page.margins.left - doc.page.margins.right;

    for (const block of document.blocks) {
      switch (block.type) {
        case "title":
          doc.fontSize(17).text(pdfText(block.text), { align: block.align ?? "left" });
          break;
        case "subtitle":
          doc.fontSize(10).fillColor("#475569").text(pdfText(block.text), {
            align: block.align ?? "left",
          });
          doc.fillColor("#0f172a");
          break;
        case "keyValues": {
          const perColumn = block.columns === 2 ? 2 : 1;
          const colWidth = usable / perColumn;
          let index = 0;
          while (index < block.items.length) {
            const y = doc.y;
            for (let c = 0; c < perColumn && index < block.items.length; c += 1) {
              const item = block.items[index] as [string, string];
              doc
                .fontSize(9)
                .fillColor("#64748b")
                .text(pdfText(item[0]), left + c * colWidth, y, { width: colWidth * 0.4, lineBreak: false });
              doc
                .fillColor("#0f172a")
                .text(pdfText(item[1]), left + c * colWidth + colWidth * 0.4, y, {
                  width: colWidth * 0.6 - 8,
                  lineBreak: false,
                });
              index += 1;
            }
            doc.moveDown(0.6);
          }
          break;
        }
        case "table": {
          const colWidth = usable / block.columns.length;
          const headerY = doc.y;
          doc.fontSize(8.5).fillColor("#0f172a");
          block.columns.forEach((label, index) => {
            doc.text(pdfText(label), left + index * colWidth, headerY, {
              width: colWidth - 4,
              align: block.align?.[index] ?? "left",
              lineBreak: false,
            });
          });
          doc.moveDown(0.4);
          doc.moveTo(left, doc.y).lineTo(left + usable, doc.y).strokeColor("#94a3b8").stroke();
          doc.moveDown(0.3);
          for (const row of block.rows) {
            if (doc.y > doc.page.height - doc.page.margins.bottom - 24) {
              doc.addPage();
            }
            const y = doc.y;
            doc.fontSize(8.5);
            row.forEach((cell, index) => {
              doc.text(pdfText(String(cell)), left + index * colWidth, y, {
                width: colWidth - 4,
                align: block.align?.[index] ?? "left",
                lineBreak: false,
              });
            });
            doc.moveDown(0.4);
          }
          break;
        }
        case "note":
          doc.fontSize(8.5).fillColor("#475569").text(pdfText(block.text));
          doc.fillColor("#0f172a");
          break;
        case "spacer":
          doc.moveDown(block.height ?? 1);
          break;
        case "signature": {
          doc.moveDown(2);
          const colWidth = usable / block.labels.length;
          const y = doc.y;
          block.labels.forEach((label, index) => {
            doc
              .moveTo(left + index * colWidth, y)
              .lineTo(left + index * colWidth + colWidth * 0.7, y)
              .strokeColor("#94a3b8")
              .stroke();
            doc.fontSize(8).fillColor("#334155").text(pdfText(label), left + index * colWidth, y + 4, {
              width: colWidth * 0.7,
            });
          });
          doc.fillColor("#0f172a");
          break;
        }
      }
    }
  });
}

function renderPdf(build: (doc: PDFKit.PDFDocument) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 40, bufferPages: true });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    try {
      registerFonts(doc);
      build(doc);
      doc.end();
    } catch (error) {
      reject(error instanceof Error ? error : new Error(String(error)));
    }
  });
}

/** CSV fallback (used by the "download raw data" button). */
export function rowsToCsv(columns: string[], rows: (string | number)[][]): string {
  const escape = (value: string | number) => {
    const text = String(value ?? "");
    return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
  };
  return [columns.map(escape).join(","), ...rows.map((row) => row.map(escape).join(","))].join("\n");
}
