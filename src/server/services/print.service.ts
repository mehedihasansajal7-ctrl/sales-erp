import { formatDate, formatDateTime } from "@/lib/dates";
import { getSettings, SETTING_KEYS } from "@/lib/settings";
import { getOrderDetail } from "@/server/services/order.service";
import { getDeliveryOrder } from "@/server/services/delivery-order.service";
import { getDispatchForPrint } from "@/server/services/dispatch.service";
import type { PrintableBlock, PrintableDocument } from "@/server/services/export.service";
import type { ServiceActor } from "@/server/services/order.service";
import { errors } from "@/lib/errors";

/**
 * Printable documents: order confirmation, DO copy and dispatch challan.
 * The same builder feeds the on-screen print page and the server-side PDF, so
 * the printed copy and the PDF can never disagree.
 */

async function companyHeader(title: string, subtitle: string): Promise<PrintableBlock[]> {
  const settings = await getSettings();
  return [
    { type: "title", text: settings[SETTING_KEYS.companyName] ?? "Bulk Commodity Trading Ltd." },
    { type: "subtitle", text: settings[SETTING_KEYS.companyAddress] ?? "" },
    { type: "subtitle", text: title },
    { type: "subtitle", text: subtitle },
    { type: "spacer", height: 0.6 },
  ];
}

export type PrintablePayload = {
  document: PrintableDocument;
  /** Structured data so the HTML print page renders the same content. */
  meta: {
    title: string;
    docNo: string;
    status: string;
    company: string;
    companyAddress: string;
  };
  keyValues: [string, string][];
  tables: { title: string; columns: string[]; rows: string[][]; align?: ("left" | "right")[] }[];
  signatures: string[];
  notes: string[];
};

export async function buildOrderPrintable(orderId: string, user: ServiceActor): Promise<PrintablePayload> {
  const order = await getOrderDetail(orderId, user);
  const settings = await getSettings();

  const keyValues: [string, string][] = [
    ["Order no", order.orderNo],
    ["Order date", formatDateTime(order.orderDate)],
    ["Customer", `${order.customerName} (${order.customerCode})`],
    ["Phone", order.customer.phone ?? "—"],
    ["Address", order.customer.address ?? "—"],
    ["Status", order.statusLabel],
    ["Priority sequence", `#${order.orderSeq} for this customer`],
    ["Created by", order.createdByName],
  ];

  const tables = [
    {
      title: "Order lines (rate locked at order time)",
      columns: ["Product", "Qty (MT)", "Locked rate (৳/MT)", "Line value (৳)"],
      rows: order.items.map((item) => [
        `${item.productName} (${item.productCode})`,
        item.qtyMt,
        item.lockedRatePerMt,
        item.lineValue,
      ]),
      align: ["left", "right", "right", "right"] as ("left" | "right")[],
    },
    {
      title: "Total",
      columns: ["", "", "Order value (৳)", order.totalValue],
      rows: [["", "", "Delivered value (৳)", order.deliveredValue]],
      align: ["left", "left", "right", "right"] as ("left" | "right")[],
    },
    {
      title: "Delivery progress",
      columns: ["Ordered (MT)", "Delivered (MT)", "Remaining (MT)"],
      rows: [[order.orderedMt, order.deliveredMt, order.remainingMt]],
      align: ["right", "right", "right"] as ("left" | "right")[],
    },
    ...(order.deliveryOrders.length
      ? [
          {
            title: "Delivery orders",
            columns: ["DO no", "Warehouse", "Status", "Qty (MT)", "Dispatched (MT)"],
            rows: order.deliveryOrders.map((row) => [
              row.doNo,
              row.warehouseName,
              row.status.replace(/_/g, " "),
              row.items.reduce((acc, item) => acc + Number(item.qtyMt), 0).toFixed(3),
              row.items.reduce((acc, item) => acc + Number(item.dispatchedMt), 0).toFixed(3),
            ]),
            align: ["left", "left", "left", "right", "right"] as ("left" | "right")[],
          },
        ]
      : []),
  ];

  const notes = [
    `Rate is locked for this order and never changes when Finance publishes a later rate.`,
    ...(order.remarks ? [`Remarks: ${order.remarks}`] : []),
  ];

  const blocks: PrintableBlock[] = [
    ...(await companyHeader("Order confirmation", `${order.orderNo} · ${order.statusLabel}`)),
    { type: "keyValues", items: keyValues, columns: 2 },
    { type: "spacer", height: 0.6 },
    ...tables.map<PrintableBlock>((table) => ({
      type: "table",
      columns: table.columns,
      rows: table.rows,
      align: table.align,
    })),
    { type: "note", text: `Generated by ${user.name} on ${formatDateTime(new Date())} (Asia/Dhaka)` },
    { type: "signature", labels: ["Prepared by", "Sales Operations", "Customer"] },
  ];

  return {
    document: { blocks },
    meta: {
      title: "Order confirmation",
      docNo: order.orderNo,
      status: order.statusLabel,
      company: settings[SETTING_KEYS.companyName] ?? "",
      companyAddress: settings[SETTING_KEYS.companyAddress] ?? "",
    },
    keyValues,
    tables,
    signatures: ["Prepared by", "Sales Operations", "Customer"],
    notes,
  };
}

export async function buildDoPrintable(doId: string, user: ServiceActor): Promise<PrintablePayload> {
  const deliveryOrder = await getDeliveryOrder(doId, user);
  const settings = await getSettings();

  const keyValues: [string, string][] = [
    ["Delivery order no", deliveryOrder.doNo],
    ["Order no", deliveryOrder.orderNo],
    ["Customer", `${deliveryOrder.customerName} (${deliveryOrder.customerCode})`],
    ["Warehouse", deliveryOrder.warehouseName],
    ["Created", `${formatDateTime(deliveryOrder.createdAt)} by ${deliveryOrder.createdByName}`],
    ["Status", deliveryOrder.statusLabel],
    [
      "Priority",
      deliveryOrder.priorityOverride
        ? `OVERRIDE — ${deliveryOrder.overrideReason ?? ""}`
        : "Normal (customer queue respected)",
    ],
  ];

  const tables = [
    {
      title: "Items",
      columns: ["Product", "DO qty (MT)", "Dispatched (MT)", "Pending (MT)"],
      rows: deliveryOrder.items.map((item) => [
        `${item.productName} (${item.productCode})`,
        item.qtyMt,
        item.dispatchedMt,
        item.remainingMt,
      ]),
      align: ["left", "right", "right", "right"] as ("left" | "right")[],
    },
    ...(deliveryOrder.dispatches.length
      ? [
          {
            title: "Dispatches against this DO",
            columns: ["Challan", "Truck", "Driver", "Qty (MT)", "Date"],
            rows: deliveryOrder.dispatches.map((dispatch) => [
              dispatch.challanNo,
              dispatch.truckNo,
              `${dispatch.driverName} (${dispatch.driverPhone})`,
              dispatch.qtyMt,
              formatDate(dispatch.dispatchDate),
            ]),
            align: ["left", "left", "left", "right", "left"] as ("left" | "right")[],
          },
        ]
      : []),
  ];

  return {
    document: {
      blocks: [
        ...(await companyHeader("Delivery order", `${deliveryOrder.doNo} · ${deliveryOrder.statusLabel}`)),
        { type: "keyValues", items: keyValues, columns: 2 },
        { type: "spacer", height: 0.6 },
        ...tables.map<PrintableBlock>((table) => ({
          type: "table",
          columns: table.columns,
          rows: table.rows,
          align: table.align,
        })),
        {
          type: "note",
          text: "The warehouse loads and dispatches against this delivery order. Quantities can never exceed the approved order.",
        },
        { type: "signature", labels: ["Warehouse in-charge", "Driver", "Received by"] },
      ],
    },
    meta: {
      title: "Delivery order",
      docNo: deliveryOrder.doNo,
      status: deliveryOrder.statusLabel,
      company: settings[SETTING_KEYS.companyName] ?? "",
      companyAddress: settings[SETTING_KEYS.companyAddress] ?? "",
    },
    keyValues,
    tables,
    signatures: ["Warehouse in-charge", "Driver", "Received by"],
    notes: ["Quantities can never exceed the approved order."],
  };
}

export async function buildChallanPrintable(dispatchId: string): Promise<PrintablePayload> {
  const dispatch = await getDispatchForPrint(dispatchId);
  const settings = await getSettings();

  const keyValues: [string, string][] = [
    ["Challan no", dispatch.challanNo],
    ["Delivery order", dispatch.doNo],
    ["Order no", dispatch.orderNo],
    ["Customer", dispatch.customerName],
    ["Address", dispatch.customerAddress ?? "—"],
    ["Warehouse", `${dispatch.warehouseName}${dispatch.warehouseLocation ? ` (${dispatch.warehouseLocation})` : ""}`],
    ["Truck / vehicle", dispatch.truckNo],
    ["Driver", `${dispatch.driverName} · ${dispatch.driverPhone}`],
    ["Loading date", formatDate(dispatch.loadingDate)],
    ["Dispatch date", formatDate(dispatch.dispatchDate)],
  ];

  const tables = [
    {
      title: "Dispatched goods",
      columns: ["SL", "Product", "Quantity (MT)"],
      rows: dispatch.items.map((item, index) => [
        String(index + 1),
        `${item.productName} (${item.productCode})`,
        item.qtyMt,
      ]),
      align: ["left", "left", "right"] as ("left" | "right")[],
    },
    {
      title: "Total",
      columns: ["", "Total quantity (MT)", dispatch.totalQtyMt],
      rows: [["", "", ""]],
      align: ["left", "right", "right"] as ("left" | "right")[],
    },
  ];

  return {
    document: {
      blocks: [
        ...(await companyHeader("Dispatch challan", dispatch.challanNo)),
        { type: "keyValues", items: keyValues, columns: 2 },
        { type: "spacer", height: 0.6 },
        ...tables.map<PrintableBlock>((table) => ({
          type: "table",
          columns: table.columns,
          rows: table.rows,
          align: table.align,
        })),
        ...(dispatch.remarks ? [{ type: "note" as const, text: `Remarks: ${dispatch.remarks}` }] : []),
        {
          type: "note",
          text: `Recorded by ${dispatch.recordedByName} on ${formatDateTime(dispatch.dispatchDate)} (Asia/Dhaka)`,
        },
        { type: "signature", labels: ["Warehouse in-charge", "Driver", "Receiver"] },
      ],
    },
    meta: {
      title: "Dispatch challan",
      docNo: dispatch.challanNo,
      status: "",
      company: settings[SETTING_KEYS.companyName] ?? "",
      companyAddress: settings[SETTING_KEYS.companyAddress] ?? "",
    },
    keyValues,
    tables,
    signatures: ["Warehouse in-charge", "Driver", "Receiver"],
    notes: dispatch.remarks ? [`Remarks: ${dispatch.remarks}`] : [],
  };
}

export type PrintableKind = "order" | "do" | "challan";

export async function buildPrintable(
  kind: string,
  id: string,
  user: ServiceActor,
): Promise<PrintablePayload> {
  switch (kind) {
    case "order":
      return buildOrderPrintable(id, user);
    case "do":
      return buildDoPrintable(id, user);
    case "challan":
      return buildChallanPrintable(id);
    default:
      throw errors.notFound("Printable document");
  }
}
